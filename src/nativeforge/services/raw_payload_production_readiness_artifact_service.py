"""Production raw payload readiness artifacts (Gate 96G).

Writes to ``artifacts/raw_payload_production_readiness/``.

Every artifact states the same eight facts, and the two that matter most are
the ones that stay false: ``production_raw_payload_store_available`` and
``production_storage_live``. The writer refuses to run if the summary carries a
phrase claiming otherwise.

The schema artifact is generated by **reading the migration file's own column
list**, not by transcribing it. A hand-copied schema drifts from the migration
the first time someone edits one and not the other.
"""

